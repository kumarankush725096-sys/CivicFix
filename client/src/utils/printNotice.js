// Every dynamic value is HTML-escaped: report text is user-controlled (XSS fix).
const esc = (v) =>
  String(v ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');

const BADGE = {
  High: 'background:#fee2e2;color:#991b1b',
  Medium: 'background:#fef3c7;color:#92400e',
  Low: 'background:#e0f2fe;color:#075985',
};

export function printNotice(report) {
  const a = report.analysis || {};
  const w = window.open('', '_blank');
  if (!w) return false; // popup blocked

  w.document.write(`<!DOCTYPE html><html><head><meta charset="utf-8">
<title>CivicFix Notice - Docket #${esc(report.id)}</title>
<style>
 body{font-family:'Segoe UI',Tahoma,sans-serif;padding:40px;color:#111}
 .header{border-bottom:2px solid #059669;padding-bottom:12px;margin-bottom:24px;display:flex;justify-content:space-between;gap:16px}
 .title{font-size:20px;font-weight:800;color:#064e3b;margin:0}
 .badge{padding:4px 10px;border-radius:4px;font-size:12px;font-weight:bold;height:fit-content;${BADGE[a.priority] || BADGE.Medium}}
 .section{margin-bottom:16px}
 .label{font-size:11px;text-transform:uppercase;color:#6b7280;font-weight:bold}
 .value{font-size:14px;margin-top:2px}
 .policy{background:#f0fdf4;border-left:4px solid #059669;padding:12px;margin-top:15px}
 .footer{margin-top:30px;border-top:1px dashed #ccc;padding-top:15px;font-size:11px;color:#666;display:flex;justify-content:space-between}
</style></head><body>
<div class="header">
  <div><div class="title">MUNICIPAL ACTION DIRECTIVE</div>
  <div style="font-size:12px;color:#555">Generated by CivicFix AI triage. Requires officer verification.</div></div>
  <div class="badge">${esc(a.priority || 'Unrated')} priority | SLA: ${esc(a.slaHours ?? 'N/A')}h</div>
</div>
<div class="section">
  <div class="label">Docket</div>
  <div class="value"><strong>#${esc(report.id)}</strong> | <strong>Authority:</strong> ${esc(a.assignedDepartment)}</div>
  <div class="value"><strong>Location:</strong> ${esc(report.location)}</div>
  <div class="value"><strong>Reported:</strong> ${esc(new Date(report.createdAt).toLocaleString())}</div>
</div>
<div class="section"><div class="label">Issue</div><div class="value"><strong>${esc(report.title)}</strong></div>
  <div class="value">${esc(a.summary)}</div></div>
<div class="section"><div class="label">Field team directive</div><div class="value">${esc(a.recommendedAction)}</div></div>
<div class="policy"><div class="label" style="color:#065f46">Applicable standard</div>
  <div class="value" style="font-family:monospace">${esc(a.applicablePolicy || 'Not specified')}</div></div>
<div class="footer"><div>CivicFix | AI-assisted, officer-verified</div><div>Officer signature: ______________________</div></div>
</body></html>`);
  w.document.close();
  w.focus();
  setTimeout(() => w.print(), 400);
  return true;
}
